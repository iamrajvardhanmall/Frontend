// Variables are containers for storing data values.


name = "Rajvardhan Mall";  // string
console.log(name);
age = 20;  // Number
console.log(age);
isStudent = true;  // Boolean
console.log(isStudent);
price = 99.99;  // Number
console.log(price);
x = null; // Null
console.log(x);
y = undefined; // Undefined
console.log(y);

name = 25;
console.log(name); // This will print 25, as the variable 'name' is now reassigned to a number

// NOTE:- Javascript is a dynamically typed language, which means that variables can hold values of any type without declaring their datatype and can be reassigned to different types at any time. 